export const getSeverity = (action: string): AuditSeverity =>
  ACTION_SEVERITY[action] ?? "INFO";

export const getLogSeverity = (
  log: Pick<AuditLogEntry, "action" | "severity">,
): AuditSeverity => {
  return log.severity ?? getSeverity(log.action);
};
